"""Cleaning for the three Superstore sections.

Every decision is recorded in a CleaningReport so it can be printed in the
README/report and checked. The raw DataFrames are never modified; cleaning
works on copies. Rows that fail validation are not dropped silently: they are
returned in a separate `rejected` table with the reason.
"""
from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np
import pandas as pd

from .analysis import safe_divide

DATE_FORMAT = "%m/%d/%Y"  # the file uses e.g. 11/8/2017

# A row cannot be analysed without these.
REQUIRED_FIELDS = [
    "Order ID", "Order Date", "Customer ID", "Customer Name", "Segment",
    "Region", "State", "Product ID", "Product Name", "Category",
    "Sub-Category", "Sales", "Quantity", "Discount", "Profit",
]
# Low-cardinality labels where "west" and "West" should be the same group.
LABEL_COLUMNS = [
    "Ship Mode", "Segment", "Country", "City", "State", "Region",
    "Category", "Sub-Category",
]
NUMERIC_COLUMNS = ["Sales", "Quantity", "Discount", "Profit"]
DUPLICATE_POLICIES = ("flag", "drop")


class CleaningError(Exception):
    """The data cannot be cleaned (e.g. a required column is missing)."""


@dataclass
class CleaningReport:
    """Ordered log of what cleaning did and why."""

    steps: list[dict] = field(default_factory=list)

    def add(self, step: str, affected: int, decision: str) -> None:
        self.steps.append(
            {"step": step, "affected": int(affected), "decision": decision}
        )

    def to_markdown(self) -> str:
        lines = [
            "# Data cleaning report",
            "",
            "Generated by the pipeline from the data it actually loaded. "
            "'Affected' counts rows unless the decision text says otherwise.",
            "",
            "| # | Step | Affected | Decision |",
            "|---|------|---------:|----------|",
        ]
        for number, item in enumerate(self.steps, start=1):
            decision = item["decision"].replace("|", "/")
            lines.append(
                f"| {number} | {item['step']} | {item['affected']:,} | {decision} |"
            )
        return "\n".join(lines) + "\n"


@dataclass
class CleanedData:
    orders: pd.DataFrame
    rejected: pd.DataFrame
    returns: pd.DataFrame
    people: pd.DataFrame
    report: CleaningReport
    returns_available: bool


# --------------------------------------------------------------------------
# helpers
# --------------------------------------------------------------------------
def _strip_and_blank_to_nan(df: pd.DataFrame) -> tuple[pd.DataFrame, int]:
    """Trim whitespace in every text cell; turn empty strings into NaN."""
    out = df.copy()
    blank_cells = 0
    for column in out.columns:
        stripped = out[column].astype("object").map(
            lambda v: v.strip() if isinstance(v, str) else v
        )
        is_blank = stripped.map(lambda v: isinstance(v, str) and v == "")
        blank_cells += int(is_blank.sum())
        out[column] = stripped.mask(is_blank, np.nan)
    return out, blank_cells


def _harmonise_case_variants(series: pd.Series) -> tuple[pd.Series, int]:
    """Map spellings that differ only by case/inner spacing to the commonest one."""
    tidy = series.map(
        lambda v: " ".join(v.split()) if isinstance(v, str) else v
    )
    counts = tidy.value_counts()
    canonical: dict[str, str] = {}
    for spelling in counts.index:  # most common first
        canonical.setdefault(spelling.lower(), spelling)
    mapped = tidy.map(lambda v: canonical[v.lower()] if isinstance(v, str) else v)
    changed = series.notna() & (mapped != series)
    return mapped, int(changed.sum())


def _parse_postal_codes(series: pd.Series) -> tuple[pd.Series, int]:
    """Keep postal codes as 5-character text; restore lost leading zeros."""
    text = series.astype("object").map(
        lambda v: v[:-2] if isinstance(v, str) and v.endswith(".0") else v
    )
    short = text.map(lambda v: isinstance(v, str) and v.isdigit() and len(v) < 5)
    padded = text.mask(short, text.map(lambda v: v.zfill(5) if isinstance(v, str) else v))
    return padded, int(short.sum())


# --------------------------------------------------------------------------
# Orders
# --------------------------------------------------------------------------
def clean_orders(
    raw_orders: pd.DataFrame,
    report: CleaningReport | None = None,
    duplicate_policy: str = "flag",
) -> tuple[pd.DataFrame, pd.DataFrame, CleaningReport]:
    """Clean the Orders section.

    Returns (clean_orders, rejected_rows, report).
    duplicate_policy:
        "flag" keeps rows that are identical apart from Row ID but marks them in
               a `possible_duplicate` column (default - see README for why);
        "drop" removes the later copy.
    """
    if duplicate_policy not in DUPLICATE_POLICIES:
        raise CleaningError(
            f"duplicate_policy must be one of {DUPLICATE_POLICIES}, "
            f"got {duplicate_policy!r}"
        )
    missing = [c for c in ["Row ID", "Ship Date", "Postal Code", *REQUIRED_FIELDS]
               if c not in raw_orders.columns]
    if missing:
        raise CleaningError(f"Orders data is missing required columns: {missing}")

    report = report or CleaningReport()
    rows_in = len(raw_orders)
    report.add("Rows loaded (Orders section only)", rows_in,
               "People and Returns blocks were split off before this point, so "
               "they are not counted as orders.")

    # 1. whitespace and blanks ------------------------------------------------
    df, blank_cells = _strip_and_blank_to_nan(raw_orders)
    report.add("Trim whitespace, blank text -> missing", blank_cells,
               "Counted in cells, not rows. Empty strings become NaN so that "
               "missing-value checks work.")

    # 2. label spelling -------------------------------------------------------
    variants_total = 0
    for column in LABEL_COLUMNS:
        if column in df.columns:
            df[column], changed = _harmonise_case_variants(df[column])
            variants_total += changed
    report.add("Harmonise label spelling (case / inner spaces)", variants_total,
               "Cells in Ship Mode, Segment, Country, City, State, Region, "
               "Category and Sub-Category were mapped to the most common "
               "spelling. Product and customer names are left untouched.")

    # 3. data types -----------------------------------------------------------
    typed = df.copy()
    unparseable: dict[str, int] = {}
    for column in NUMERIC_COLUMNS:
        # always float64, even if every value in the file is a whole number
        converted = pd.to_numeric(df[column], errors="coerce").astype("float64")
        unparseable[column] = int((df[column].notna() & converted.isna()).sum())
        typed[column] = converted
    for column in ["Order Date", "Ship Date"]:
        converted = pd.to_datetime(df[column], format=DATE_FORMAT, errors="coerce")
        unparseable[column] = int((df[column].notna() & converted.isna()).sum())
        typed[column] = converted
    typed["Row ID"] = pd.to_numeric(df["Row ID"], errors="coerce").astype("Int64")
    typed["Postal Code"], padded = _parse_postal_codes(df["Postal Code"])
    report.add("Convert Sales/Quantity/Discount/Profit to numbers and dates "
               "to datetime", sum(unparseable.values()),
               f"Values that could not be parsed (counted in cells): {unparseable}. "
               f"Dates use the fixed format {DATE_FORMAT}; anything else becomes "
               "missing and is rejected below.")
    report.add("Postal Code kept as text, leading zeros restored", padded,
               "Codes shorter than 5 digits (e.g. 1040) were left-padded with "
               "zeros (01040). Postal Code is an identifier, not a number.")

    # 4. invalid records ------------------------------------------------------
    masks: dict[str, pd.Series] = {}
    for column in REQUIRED_FIELDS:
        masks[f"missing or unparseable {column}"] = typed[column].isna()
    masks["unparseable Ship Date"] = df["Ship Date"].notna() & typed["Ship Date"].isna()
    qty = typed["Quantity"]
    masks["Quantity not a whole number >= 1"] = qty.notna() & ((qty < 1) | (qty % 1 != 0))
    masks["Sales <= 0"] = typed["Sales"].notna() & (typed["Sales"] <= 0)
    masks["Discount outside 0-1"] = typed["Discount"].notna() & (
        (typed["Discount"] < 0) | (typed["Discount"] > 1))
    masks["Profit not finite"] = typed["Profit"].notna() & ~np.isfinite(
        typed["Profit"].astype("float64"))
    masks["Ship Date before Order Date"] = (
        typed["Ship Date"].notna() & typed["Order Date"].notna()
        & (typed["Ship Date"] < typed["Order Date"]))

    mask_frame = pd.DataFrame(masks)
    reject = mask_frame.any(axis=1)
    rejected = raw_orders.loc[reject].copy()
    if reject.any():
        rejected["reject_reason"] = mask_frame[reject].apply(
            lambda row: "; ".join(row.index[row.values.astype(bool)]), axis=1)
    else:
        rejected["reject_reason"] = pd.Series(dtype="object")

    counts = {name: int(mask.sum()) for name, mask in masks.items()}
    nonzero = {k: v for k, v in counts.items() if v}
    report.add("Validity checks (missing key fields, Sales <= 0, bad Quantity, "
               "Discount outside 0-1, non-finite Profit, ship before order)",
               int(reject.sum()),
               f"{len(masks)} rules checked. Rows breaking any rule are moved to "
               "a separate rejected table with the reason, not silently "
               f"dropped. Rows failing per rule: {nonzero if nonzero else 'none'}.")

    valid = typed.loc[~reject].copy()

    # 5. duplicates -----------------------------------------------------------
    exact = valid.duplicated(keep="first")
    report.add("Exact duplicate rows (all columns incl. Row ID)", int(exact.sum()),
               "Identical in every column, so a re-loaded record: the later copy "
               "is removed.")
    valid = valid.loc[~exact].copy()

    row_id_dups = int(valid["Row ID"].dropna().duplicated().sum())
    report.add("Row ID uniqueness check", row_id_dups,
               "Row ID is only a sequence number. Repeats would be reported "
               "here but rows are not removed because other fields differ.")

    content_columns = [c for c in valid.columns if c != "Row ID"]
    ambiguous = valid.duplicated(subset=content_columns, keep="first")
    dup_sales = float(valid.loc[ambiguous, "Sales"].sum())
    dup_share = safe_divide(dup_sales, float(valid["Sales"].sum()))
    if duplicate_policy == "flag":
        valid["possible_duplicate"] = ambiguous
        decision = (
            "Identical in every column except Row ID. Row ID differs, and the "
            "same product can legitimately appear twice in one order, so there "
            "is no proof these are errors: KEPT and flagged in "
            "`possible_duplicate`. Their Sales are "
            f"{dup_sales:,.2f} ({dup_share:.4%} of total), so the conclusion "
            "does not depend on this choice. Use --duplicate-policy drop to "
            "remove them.")
    else:
        valid = valid.loc[~ambiguous].copy()
        valid["possible_duplicate"] = False
        decision = (
            "Identical in every column except Row ID: later copy REMOVED "
            f"(policy 'drop'). Removed Sales: {dup_sales:,.2f} "
            f"({dup_share:.4%} of total).")
    report.add("Ambiguous duplicates (same except Row ID)", int(ambiguous.sum()),
               decision)

    # 6. missing values that remain ------------------------------------------
    missing_postal = int(valid["Postal Code"].isna().sum())
    report.add("Missing Postal Code (kept as missing)", missing_postal,
               "Not imputed: inventing a postal code would fabricate data, and "
               "no analysis here uses it. City/State for these rows are present.")

    # 7. product identity -----------------------------------------------------
    names_per_id = valid.groupby("Product ID")["Product Name"].nunique()
    report.add("Product IDs with more than one product name",
               int((names_per_id > 1).sum()),
               "Counted in Product IDs. Product ID alone is not a reliable key, "
               "so product-level analysis groups by Product ID + Product Name "
               "(+ Category/Sub-Category).")

    # 8. derived columns ------------------------------------------------------
    valid["Quantity"] = valid["Quantity"].astype("int64")
    valid["order_year"] = valid["Order Date"].dt.year.astype("int64")
    valid["order_month_num"] = valid["Order Date"].dt.month.astype("int64")
    valid["order_month"] = valid["Order Date"].dt.to_period("M").dt.to_timestamp()
    valid["ship_days"] = (valid["Ship Date"] - valid["Order Date"]).dt.days
    valid["row_margin"] = safe_divide(valid["Profit"], valid["Sales"])
    valid["is_loss"] = valid["Profit"] < 0
    valid["is_returned"] = False  # filled in by flag_returned_orders
    report.add("Derived columns added", len(valid),
               "order_year, order_month, order_month_num, ship_days, row_margin "
               "(Profit / Sales per line; Sales > 0 is guaranteed by the "
               "validity checks), is_loss (Profit < 0), is_returned.")

    valid = valid.reset_index(drop=True)
    report.add("Rows kept for analysis", len(valid),
               f"{rows_in:,} loaded -> {len(valid):,} kept, "
               f"{len(rejected):,} rejected, "
               f"{rows_in - len(valid) - len(rejected):,} removed as duplicates.")
    return valid, rejected.reset_index(drop=True), report


# --------------------------------------------------------------------------
# Returns and People
# --------------------------------------------------------------------------
def clean_returns(raw_returns: pd.DataFrame, report: CleaningReport) -> pd.DataFrame:
    """Return one row per returned Order ID."""
    if raw_returns.empty:
        report.add("Returns section", 0,
                   "Missing or empty in the file: returned-order analysis is skipped.")
        return pd.DataFrame(columns=["Order ID"])

    df, _ = _strip_and_blank_to_nan(raw_returns)
    report.add("Returns rows loaded", len(df),
               "Rows in the Returns block. The same Order ID can appear on "
               "several rows.")
    blank_ids = df["Order ID"].isna()
    report.add("Returns rows without an Order ID", int(blank_ids.sum()),
               "Cannot be matched to an order, so they are dropped.")
    df = df.loc[~blank_ids]

    is_yes = df["Returned"].fillna("").str.lower().eq("yes")
    report.add("Returns rows whose Returned value is not 'Yes'", int((~is_yes).sum()),
               "Only 'Yes' is treated as a return; anything else is ignored.")
    df = df.loc[is_yes]

    before = len(df)
    unique = df[["Order ID"]].drop_duplicates().reset_index(drop=True)
    report.add("Repeated Order IDs in Returns", before - len(unique),
               "The Returns block repeats order IDs; the return flag is "
               "order-level, so each order is counted once "
               f"({len(unique):,} unique returned orders).")
    return unique


def flag_returned_orders(
    orders: pd.DataFrame, returned_ids: pd.DataFrame, report: CleaningReport
) -> pd.DataFrame:
    """Set `is_returned` on every line of a returned order."""
    out = orders.copy()
    ids = set(returned_ids["Order ID"])
    out["is_returned"] = out["Order ID"].isin(ids)
    unmatched = len(ids - set(out["Order ID"]))
    report.add("Returned Order IDs not found in Orders", unmatched,
               "Cannot be linked to any sales line (or the order was rejected); "
               "they are ignored.")
    report.add("Order lines flagged as belonging to a returned order",
               int(out["is_returned"].sum()),
               "The source has only an order-level flag (no return date, "
               "amount or reason), so every line of the order is flagged.")
    return out


def clean_people(raw_people: pd.DataFrame, orders: pd.DataFrame,
                 report: CleaningReport) -> pd.DataFrame:
    if raw_people.empty:
        report.add("People section", 0, "Missing or empty in the file; skipped.")
        return pd.DataFrame(columns=["Person", "Region"])
    df, _ = _strip_and_blank_to_nan(raw_people)
    df = df.dropna(subset=["Person", "Region"])
    before = len(df)
    df = df.drop_duplicates(subset="Region", keep="first").reset_index(drop=True)
    report.add("People rows (Person per Region)", len(df),
               f"{before - len(df)} repeated regions dropped (first kept). The "
               "file does not say what the Person's role is, so the report "
               "only calls them 'person listed for the region'.")
    unknown = set(df["Region"]) - set(orders["Region"])
    report.add("People regions not present in Orders", len(unknown),
               "Counted in regions; such rows are harmless and ignored.")
    return df


def prepare_data(sections: dict[str, pd.DataFrame],
                 duplicate_policy: str = "flag") -> CleanedData:
    """Run all cleaning steps on the output of load_data.read_sections."""
    report = CleaningReport()
    orders, rejected, report = clean_orders(
        sections["orders"], report, duplicate_policy)
    returns = clean_returns(sections.get("returns", pd.DataFrame()), report)
    returns_available = not returns.empty
    orders = flag_returned_orders(orders, returns, report)
    people = clean_people(sections.get("people", pd.DataFrame()), orders, report)
    return CleanedData(orders, rejected, returns, people, report, returns_available)
